      sheet.getRangeByIndex(row, 4).setFormula('SUM(D$dataStartRow:D$dataEndRow)');
      sheet.getRangeByIndex(row, 5).setFormula('SUM(E$dataStartRow:E$dataEndRow)');
      sheet.getRangeByIndex(row, 6).setFormula('SUM(F$dataStartRow:F$dataEndRow)');
      // Costo total = suma de costos individuales
      sheet.getRangeByIndex(row, 8).setFormula('SUM(H$dataStartRow:H$dataEndRow)');
      sheet.getRangeByIndex(row, 8).numberFormat = _currencyFormat;
    }
    row += 2;

    // === RESUMEN ===
    for (var i = 0; i < 8; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.cellStyle.bold = true;
      cell.cellStyle.fontSize = 11;
