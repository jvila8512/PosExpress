  /// Retorna la lista de archivos exportados guardados en la carpeta interna.
  /// Cada entry tiene: name, path, size, lastModified, type (pdf/excel).
  Future<List<Map<String, dynamic>>> getExportsList() async {
    final exportsDir = await _getExportsDir();
    final dir = Directory(exportsDir);
    if (!await dir.exists()) return [];

    final files = <Map<String, dynamic>>[];
    await for (final entity in dir.list()) {
      if (entity is File) {
        final stat = await entity.stat();
        final name = entity.path.split('/').last;
        files.add({
          'name': name,
          'path': entity.path,
          'size': stat.size,
          'lastModified': stat.modified,
          'type': name.endsWith('.pdf')
              ? 'pdf'
              : name.endsWith('.xlsx')
                  ? 'excel'
                  : 'other',
        });
      }
    }
    // Ordenar por fecha descendente (más reciente primero)
    files.sort((a, b) {
      final da = a['lastModified'] as DateTime;
      final db = b['lastModified'] as DateTime;
      return db.compareTo(da);
    });
    return files;
  }

  /// Guarda el archivo exportado en una ubicación visible en el teléfono.
  /// 
  /// Estrategia (de más a menos conveniente):
  /// 1. Ruta directa /storage/emulated/0/NegocioJV/Exportaciones/ (Android ≤10)
  /// 2. Carpeta Downloads/Descargas: /storage/emulated/0/Download/NegocioJV/Exportaciones/
  /// 3. FilePicker SAF dialog (fallback universal, funciona en todos los Android)
  Future<String?> saveToExportsDir(String filePath) async {
    try {
      final sourceFile = File(filePath);
      if (!await sourceFile.exists()) return null;

      final fileName = filePath.split('/').last;
      final bytes = await sourceFile.readAsBytes();

      String? destPath;

      // 1. Ruta directa en raíz del storage (visible en gestor de archivos)
      if (Platform.isAndroid) {
        final rootPaths = [
          '/storage/emulated/0/NegocioJV/Exportaciones',     // Android ≤10 + algunos 11+
          '/storage/emulated/0/Download/NegocioJV/Exportaciones', // Descargas (más accesible)
        ];
        for (final path in rootPaths) {
          try {
            final dir = Directory(path);
            if (!await dir.exists()) {
              await dir.create(recursive: true);
            }
            destPath = dir.path;
            break; // primera que funciona, la uso
          } catch (_) {
            debugPrint('[saveToExportsDir] Path failed: $path');
          }
        }
      }

      // 2. Si no se pudo, usar FilePicker (SAF — siempre funciona en Android 11+)
      if (destPath == null) {
        return saveToDownloads(filePath);
      }

      final destFile = File('$destPath/$fileName');
      await destFile.writeAsBytes(bytes, flush: true);

      return destFile.path;
    } catch (e) {
      debugPrint('[saveToExportsDir] Error: $e');
      // 3. Fallback al FilePicker
      return saveToDownloads(filePath);
    }
  }

  /// Abre un archivo con la aplicación predeterminada del sistema.
  /// Usa open_filex que maneja content:// URIs correctamente en Android.
  Future<bool> openFile(String filePath) async {
    try {
      final result = await OpenFilex.open(filePath);
      return result.type == ResultType.done;
    } catch (e) {
      debugPrint('[openFile] Error: $e');
      return false;
    }
  }

  /// Elimina un archivo exportado de la carpeta interna de exports.
  Future<bool> deleteExport(String filePath) async {
    try {
      final file = File(filePath);
      if (await file.exists()) {
        await file.delete();
        return true;
      }
      return false;
    } catch (e) {
      debugPrint('[deleteExport] Error: $e');
      return false;
    }
  }

  /// Elimina todos los archivos de exportaciones
  Future<int> deleteAllExports() async {
    try {
      final dirPath = await _getExportsDir();
      final dir = Directory(dirPath);
      final files = dir.listSync().whereType<File>().toList();
      int deleted = 0;
      for (final file in files) {
        try {
          await file.delete();
          deleted++;
        } catch (_) {}
      }
      return deleted;
    } catch (e) {
      debugPrint('[deleteAllExports] Error: $e');
      return 0;
    }
  }

  /// Limpieza automática semanal: elimina archivos de más de 7 días
  Future<void> weeklyCleanupExports() async {
    try {
      final dirPath = await _getExportsDir();
      final dir = Directory(dirPath);
      final now = DateTime.now();
      final cutoff = now.subtract(const Duration(days: 7));
      final files = dir.listSync().whereType<File>().toList();
      for (final file in files) {
        try {
          final stat = await file.stat();
          if (stat.modified.isBefore(cutoff)) {
            await file.delete();
          }
        } catch (_) {}
      }
    } catch (_) {}
  }

  /// Formatea tamaño de archivo para mostrar (bytes → KB/MB)
  String formatFileSize(int bytes) {
    if (bytes < 1024) return '$bytes B';
    if (bytes < 1024 * 1024) return '${(bytes / 1024).toStringAsFixed(1)} KB';
    return '${(bytes / (1024 * 1024)).toStringAsFixed(1)} MB';
  }

