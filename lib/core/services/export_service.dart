  Future<String> exportProductsExcel() async {
    final products = await _db.getAllProducts();
    final categories = await _db.getAllCategories();
    final catMap = {for (final c in categories) c.id: c.name};
    final headerInfo = await _getReportHeaderInfo();

    final workbook = xlsx.Workbook();
    final sheet = workbook.worksheets[0];
    sheet.name = 'Productos';

    final colCount = 7;
    final dataStartRow = _writeExcelHeader(
      sheet: sheet,
      info: headerInfo,
      reportTitle: 'Lista de Productos',
      colSpan: colCount,
    );

    final headers = [
      'Nombre',
      'Codigo',
      'Categoria',
      'Precio Venta',
      'Precio Costo',
      'Stock',
      'Estado',
    ];
    for (var i = 0; i < headers.length; i++) {
      final cell = sheet.getRangeByIndex(dataStartRow, i + 1);
      cell.setText(headers[i]);
      cell.cellStyle.bold = true;
      cell.cellStyle.backColor = '#4472C4';
      cell.cellStyle.fontColor = '#FFFFFF';
    }

    for (var i = 0; i < products.length; i++) {
      final p = products[i];
      final row = dataStartRow + i + 1;
      sheet.getRangeByIndex(row, 1).setText(p.name);
      sheet.getRangeByIndex(row, 2).setText(p.code ?? '');
      sheet
          .getRangeByIndex(row, 3)
          .setText(catMap[p.categoryId] ?? 'Sin categoria');
      sheet.getRangeByIndex(row, 4).setNumber(p.unitPrice);
      sheet.getRangeByIndex(row, 4).numberFormat = _currencyFormat;
      sheet.getRangeByIndex(row, 5).setNumber(p.costPrice);
      sheet.getRangeByIndex(row, 5).numberFormat = _currencyFormat;

      final lots = await _db.getActiveLots(p.id);
      double stock = 0;
      for (final lot in lots) {
        stock += lot.remainingQuantity;
      }
      sheet.getRangeByIndex(row, 6).setNumber(stock);
      sheet.getRangeByIndex(row, 7).setText(p.isActive ? 'Activo' : 'Inactivo');
    }

    final lastRow = dataStartRow + products.length;
    sheet.getRangeByName('A1:G$lastRow').autoFitColumns();

    final bytes = workbook.saveAsStream();
    workbook.dispose();

    final dir = await _getExportsDir();
    final fileName =
        'Productos_${_fileDateFormatter.format(DateTime.now())}.xlsx';
    final file = File('$dir/$fileName');
    await file.writeAsBytes(bytes);

    return file.path;
  }

