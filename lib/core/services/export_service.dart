  Future<String> exportInventoryExcel() async {
    final products = await _db.getAllProducts();
    final headerInfo = await _getReportHeaderInfo();
    final workbook = xlsx.Workbook();
    final sheet = workbook.worksheets[0];
    sheet.name = 'Inventario';

    final colCount = 7;
    final dataStartRow = _writeExcelHeader(
      sheet: sheet,
      info: headerInfo,
      reportTitle: 'Informe de Inventario',
      colSpan: colCount,
    );

    final headers = [
      'Producto',
      'Stock',
      'Costo Unitario',
      'Valor Costo',
      'Precio Venta',
      'Valor Venta',
      'Ganancia Potencial',
    ];
    for (var i = 0; i < headers.length; i++) {
      final cell = sheet.getRangeByIndex(dataStartRow, i + 1);
      cell.setText(headers[i]);
      cell.cellStyle.bold = true;
      cell.cellStyle.backColor = '#2E7D32';
      cell.cellStyle.fontColor = '#FFFFFF';
      if (i > 0) cell.cellStyle.hAlign = xlsx.HAlignType.center;
    }

    var row = dataStartRow + 1;
    for (var i = 0; i < products.length; i++) {
      final p = products[i];
      final lots = await _db.getActiveLots(p.id);
      double stock = 0;
      double totalCost = 0;
      for (final lot in lots) {
        stock += lot.remainingQuantity;
        totalCost += lot.remainingQuantity * lot.costPerUnit;
      }
      if (stock <= 0) continue;

      final avgCost = stock > 0 ? totalCost / stock : p.costPrice;
      final costValue = totalCost;
      final saleValue = stock * p.unitPrice;
      final potential = saleValue - costValue;

      // Product row
      sheet.getRangeByIndex(row, 1).setText(p.name);
      final stockCell = sheet.getRangeByIndex(row, 2);
      stockCell.setNumber(stock);
      stockCell.cellStyle.hAlign = xlsx.HAlignType.center;
      final avgCostCell = sheet.getRangeByIndex(row, 3);
      avgCostCell.setNumber(avgCost);
      avgCostCell.numberFormat = _currencyFormat;
      avgCostCell.cellStyle.hAlign = xlsx.HAlignType.center;
      final costValueCell = sheet.getRangeByIndex(row, 4);
      costValueCell.setNumber(costValue);
      costValueCell.numberFormat = _currencyFormat;
      costValueCell.cellStyle.hAlign = xlsx.HAlignType.center;
      final unitPriceCell = sheet.getRangeByIndex(row, 5);
      unitPriceCell.setNumber(p.unitPrice);
      unitPriceCell.numberFormat = _currencyFormat;
      unitPriceCell.cellStyle.hAlign = xlsx.HAlignType.center;
      final saleValueCell = sheet.getRangeByIndex(row, 6);
      saleValueCell.setNumber(saleValue);
      saleValueCell.numberFormat = _currencyFormat;
      saleValueCell.cellStyle.hAlign = xlsx.HAlignType.center;
      final potentialCell = sheet.getRangeByIndex(row, 7);
      potentialCell.setNumber(potential);
      potentialCell.numberFormat = _currencyFormat;
      potentialCell.cellStyle.hAlign = xlsx.HAlignType.center;
      row++;

      // Lot detail rows (indented, with light green background)
      if (lots.isNotEmpty) {
        for (final lot in lots) {
          if (lot.remainingQuantity <= 0) continue;

          final labelCell = sheet.getRangeByIndex(row, 1);
          labelCell.setText(
            '   Lote #${lot.id} - ${lot.supplier ?? "S/Proveedor"} - ${_dateFormatter.format(lot.purchaseDate)}',
          );
          labelCell.cellStyle.backColor = '#E8F5E9';
          labelCell.cellStyle.fontColor = '#555555';
          labelCell.cellStyle.italic = true;

          final lotQtyCell = sheet.getRangeByIndex(row, 2);
          lotQtyCell.setNumber(lot.remainingQuantity);
          lotQtyCell.cellStyle.backColor = '#E8F5E9';
          lotQtyCell.cellStyle.fontColor = '#555555';
          lotQtyCell.cellStyle.italic = true;
          lotQtyCell.cellStyle.hAlign = xlsx.HAlignType.center;

          final lotCostCell = sheet.getRangeByIndex(row, 3);
          lotCostCell.setNumber(lot.costPerUnit);
          lotCostCell.numberFormat = _currencyFormat;
          lotCostCell.cellStyle.backColor = '#E8F5E9';
          lotCostCell.cellStyle.fontColor = '#555555';
          lotCostCell.cellStyle.italic = true;
          lotCostCell.cellStyle.hAlign = xlsx.HAlignType.center;

          // Lot total cost
          final lotTotalCell = sheet.getRangeByIndex(row, 4);
          lotTotalCell.setNumber(lot.remainingQuantity * lot.costPerUnit);
          lotTotalCell.numberFormat = _currencyFormat;
          lotTotalCell.cellStyle.backColor = '#E8F5E9';
          lotTotalCell.cellStyle.fontColor = '#555555';
          lotTotalCell.cellStyle.italic = true;
          lotTotalCell.cellStyle.hAlign = xlsx.HAlignType.center;

          // Empty cells for cols 5-7
          for (var c = 5; c <= 7; c++) {
            final emptyCell = sheet.getRangeByIndex(row, c);
            emptyCell.setText('');
            emptyCell.cellStyle.backColor = '#E8F5E9';
          }
          row++;
        }
      }
    }

    sheet.getRangeByName('A1:G$row').autoFitColumns();

    final bytes = workbook.saveAsStream();
    workbook.dispose();

    final dir = await _getExportsDir();
    final fileName =
        'Inventario_${_fileDateFormatter.format(DateTime.now())}.xlsx';
    final file = File('$dir/$fileName');
    await file.writeAsBytes(bytes);

    return file.path;
  }

