  /// Excel de transferencias de una caja específica
  Future<String> exportSessionTransferExcel(Session session) async {
    final orders = await _db.getPaidOrdersBySession(session.id);
    final sellerName = await _getSellerName(session.userId);
    final headerInfo = await _getReportHeaderInfo();

    final transferPayments = <OrderPayment>[];
    for (final order in orders) {
      final payments = await _db.getOrderPayments(order.id);
      for (final p in payments) {
        if (p.paymentMethod == 'transferencia' && p.amount > 0) {
          transferPayments.add(p);
        }
      }
    }

    final workbook = xlsx.Workbook();
    final sheet = workbook.worksheets[0];
    sheet.name = 'Transferencias';

    final colCount = 10;
    int row = 1;

    // Header background
    for (var i = 0; i < colCount; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.cellStyle.bold = true;
      cell.cellStyle.fontSize = 14;
      cell.cellStyle.backColor = '#7B1FA2';
      cell.cellStyle.fontColor = '#FFFFFF';
    }
    sheet.getRangeByIndex(row, 1).setText('Transferencias - Caja');
    row++;

    // Business name
    for (var i = 0; i < colCount; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.cellStyle.fontSize = 11;
      cell.cellStyle.backColor = '#9C27B0';
      cell.cellStyle.fontColor = '#FFFFFF';
    }
    sheet.getRangeByIndex(row, 1).setText(headerInfo.businessName);
    row++;

    // Date + seller
    for (var i = 0; i < colCount; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.cellStyle.fontSize = 9;
      cell.cellStyle.backColor = '#AB47BC';
      cell.cellStyle.fontColor = '#FFFFFF';
    }
    final dateStr = DateFormat('dd/MM/yyyy').format(session.openingTime);
    sheet.getRangeByIndex(row, 1).setText('$dateStr - $sellerName');
    row++;
    row++; // blank row

    // Column headers
    final headers = [
      'Tipo',
      'Hora',
      'Monto',
      'No. Transaccion',
      'Id Compra',
      'Nombre Cliente',
      'Celular',
      'CI',
      'Fecha Transf.',
      'Referencia',
    ];
    for (var i = 0; i < headers.length; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.setText(headers[i]);
      cell.cellStyle.bold = true;
      cell.cellStyle.backColor = '#7B1FA2';
      cell.cellStyle.fontColor = '#FFFFFF';
    }
    row++;

    // Data rows
    double totalAmount = 0;
    for (final tp in transferPayments) {
      final bank = tp.bank?.isNotEmpty == true ? tp.bank! : 'Bancaria';
      sheet.getRangeByIndex(row, 1).setText(bank);
      sheet.getRangeByIndex(row, 2).setText(DateFormat('HH:mm').format(tp.createdAt));
      sheet.getRangeByIndex(row, 3).setNumber(tp.amount);
      sheet.getRangeByIndex(row, 3).numberFormat = _currencyFormat;
      sheet.getRangeByIndex(row, 4).setText(tp.transactionId ?? '');
      sheet.getRangeByIndex(row, 5).setText(tp.purchaseId ?? '');
      sheet.getRangeByIndex(row, 6).setText(tp.clientName ?? '');
      sheet.getRangeByIndex(row, 7).setText(tp.clientPhone ?? '');
      sheet.getRangeByIndex(row, 8).setText(tp.clientCI ?? '');
      sheet.getRangeByIndex(row, 9).setText(tp.transferDate ?? '');
      sheet.getRangeByIndex(row, 10).setText(tp.reference ?? '');
      totalAmount += tp.amount;
      row++;
    }

    // Total row
    for (var i = 0; i < colCount; i++) {
      sheet.getRangeByIndex(row, i + 1).cellStyle.bold = true;
      sheet.getRangeByIndex(row, i + 1).cellStyle.backColor = '#E1BEE7';
    }
    sheet.getRangeByIndex(row, 1).setText('TOTAL');
    sheet.getRangeByIndex(row, 3).setNumber(totalAmount);
    sheet.getRangeByIndex(row, 3).numberFormat = _currencyFormat;

    // Count by type
    row++;
    final typeCounts = <String, double>{};
    for (final tp in transferPayments) {
      final bank = tp.bank?.isNotEmpty == true ? tp.bank! : 'Bancaria';
      typeCounts[bank] = (typeCounts[bank] ?? 0) + tp.amount;
    }
    for (final entry in typeCounts.entries) {
      sheet.getRangeByIndex(row, 1).setText(entry.key);
      sheet.getRangeByIndex(row, 1).cellStyle.bold = true;
      sheet.getRangeByIndex(row, 3).setNumber(entry.value);
      sheet.getRangeByIndex(row, 3).numberFormat = _currencyFormat;
      row++;
    }

    sheet.getRangeByName('A1:J${row - 1}').autoFitColumns();

    final bytes = workbook.saveAsStream();
    workbook.dispose();

    final dir = await _getExportsDir();
    final sellerClean = sellerName.replaceAll(' ', '_');
    final fileDate = DateFormat('yyyy-MM-dd').format(session.openingTime);
    final fileName = 'Transferencias_Caja_${sellerClean}_$fileDate.xlsx';
    final file = File('$dir/$fileName');
    await file.writeAsBytes(bytes);

    return file.path;
  }

