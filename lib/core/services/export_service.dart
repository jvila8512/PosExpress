  Future<String> exportSessionIpvExcel(Session session, InventorySnapshot? openSnapshot, {InventorySnapshot? closeSnapshot}) async {
    final headerInfo = await _getReportHeaderInfo();
    final sellerName = await _getSellerName(session.userId);
    final workbook = xlsx.Workbook();
    final dateRangeStr = DateFormat('dd/MM/yyyy HH:mm').format(session.openingTime);

    // Parsear snapshots
    List<Map<String, dynamic>> openItems = [];
    List<Map<String, dynamic>> closeItems = [];
    try {
      if (openSnapshot != null) {
        openItems = (jsonDecode(openSnapshot.snapshotData) as List).cast<Map<String, dynamic>>();
      }
    } catch (_) {}
    try {
      if (closeSnapshot != null) {
        closeItems = (jsonDecode(closeSnapshot.snapshotData) as List).cast<Map<String, dynamic>>();
      }
    } catch (_) {}

    // Mapear stock final por nombre
    final closeMap = <String, double>{};
    for (final item in closeItems) {
      final name = item['name']?.toString() ?? '';
      closeMap[name] = (item['quantity'] as num?)?.toDouble() ?? 0;
    }

    // SHEET 1: IPV
    final sheet = workbook.worksheets[0];
    sheet.name = 'IPV';

    int row = _writeExcelHeader(
      sheet: sheet,
      info: headerInfo,
      reportTitle: 'IPV - CAJA $dateRangeStr - $sellerName',
      colSpan: 8,
    );

    final headers = ['Producto', 'Stock Inicial', 'Stock Final', 'Vendido', 'Costo Unit.', 'Valor Costo', 'Precio Venta', 'Margen %'];
    for (var i = 0; i < headers.length; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.setText(headers[i]);
      cell.cellStyle.bold = true;
      cell.cellStyle.backColor = '#1565C0';
      cell.cellStyle.fontColor = '#FFFFFF';
    }

    double totalCost = 0;
    double totalQty = 0;
    double totalCloseQty = 0;

    for (var i = 0; i < openItems.length; i++) {
      final item = openItems[i];
      final r = row + i + 1;
      final name = item['name']?.toString() ?? '';
      final qty = (item['quantity'] as num?)?.toDouble() ?? 0;
      final costPerUnit = (item['costPerUnit'] as num?)?.toDouble() ?? 0;
      final costValue = (item['totalValue'] as num?)?.toDouble() ?? 0;
      final salePrice = (item['salePrice'] as num?)?.toDouble() ?? 0;
      final closeQty = closeMap[name] ?? 0;
      final soldQty = qty - closeQty;

      sheet.getRangeByIndex(r, 1).setText(name);
      sheet.getRangeByIndex(r, 2).setNumber(qty);
      sheet.getRangeByIndex(r, 3).setNumber(closeQty);
      sheet.getRangeByIndex(r, 4).setNumber(soldQty);
      sheet.getRangeByIndex(r, 5).setNumber(costPerUnit);
      sheet.getRangeByIndex(r, 5).numberFormat = _currencyFormat;
      sheet.getRangeByIndex(r, 6).setNumber(costValue);
      sheet.getRangeByIndex(r, 6).numberFormat = _currencyFormat;
      sheet.getRangeByIndex(r, 7).setNumber(salePrice);
      sheet.getRangeByIndex(r, 7).numberFormat = _currencyFormat;
      final saleValue = qty * salePrice;
      final margin = costValue > 0 ? ((saleValue - costValue) / costValue * 100) : 0;
      sheet.getRangeByIndex(r, 8).setNumber(margin.toDouble());
      sheet.getRangeByIndex(r, 8).numberFormat = '0.0"%"';

      totalCost += costValue;
      totalQty += qty;
      totalCloseQty += closeQty;
    }

    // Totales
    final totalRow = row + openItems.length + 1;
    sheet.getRangeByIndex(totalRow, 1).setText('TOTALES');
    sheet.getRangeByIndex(totalRow, 1).cellStyle.bold = true;
    sheet.getRangeByIndex(totalRow, 2).setNumber(totalQty);
    sheet.getRangeByIndex(totalRow, 3).setNumber(totalCloseQty);
    sheet.getRangeByIndex(totalRow, 4).setNumber(totalQty - totalCloseQty);
    sheet.getRangeByIndex(totalRow, 6).setNumber(totalCost);
    sheet.getRangeByIndex(totalRow, 6).numberFormat = _currencyFormat;
    sheet.getRangeByIndex(totalRow, 6).cellStyle.bold = true;

    sheet.getRangeByName('A1:H$totalRow').autoFitColumns();

