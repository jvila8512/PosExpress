  /// Reporte de Ventas — formato similar al Excel de referencia
  /// Tabla: Producto | Inicio | Entrada | Vendido | Final | Costo | Ventas
  /// Con fórmulas para Disponible, Final y Ventas
  Future<String> exportReporteVentasExcel(Session session) async {
    final orders = await _db.getPaidOrdersBySession(session.id);
    final sellerName = await _getSellerName(session.userId);
    final headerInfo = await _getReportHeaderInfo();

    // Load inventory snapshots
    final openSnapshot = await _db.getSnapshotBySession(session.id);
    final closeSnapshot = await _db.getClosingSnapshotBySession(session.id);

    final openStock = <String, double>{};
    final closeStock = <String, double>{};
    try {
      if (openSnapshot != null) {
        final raw = jsonDecode(openSnapshot.snapshotData) as List<dynamic>;
        for (final item in raw) {
          final name = item['name'] as String? ?? '';
          final qty = (item['quantity'] as num?)?.toDouble() ?? 0;
          openStock[name] = qty;
        }
      }
    } catch (_) {}
    try {
      if (closeSnapshot != null) {
        final raw = jsonDecode(closeSnapshot.snapshotData) as List<dynamic>;
        for (final item in raw) {
          final name = item['name'] as String? ?? '';
          final qty = (item['quantity'] as num?)?.toDouble() ?? 0;
          closeStock[name] = qty;
        }
      }
    } catch (_) {}

    // Aggregate products sold
    final productsData = <String, Map<String, dynamic>>{};
    for (final order in orders) {
      final items = await _db.getOrderItems(order.id);
      for (final item in items) {
        final name = item.productName;
        if (productsData.containsKey(name)) {
          productsData[name]!['vendido'] =
              (productsData[name]!['vendido'] as double) + item.quantity;
          productsData[name]!['costoTotal'] =
              (productsData[name]!['costoTotal'] as double) +
              (item.costPrice * item.quantity);
        } else {
          productsData[name] = {
            'vendido': item.quantity,
            'costoTotal': item.costPrice * item.quantity,
            'costPrice': item.costPrice,
          };
        }
      }
    }

    final workbook = xlsx.Workbook();
    final sheet = workbook.worksheets[0];
    sheet.name = 'Reporte de Ventas';

    // === HEADER BLOCK ===
    int row = 1;

    // Row 1: Report title
    for (var i = 0; i < 8; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.cellStyle.bold = true;
      cell.cellStyle.fontSize = 14;
      cell.cellStyle.backColor = '#1A237E';
      cell.cellStyle.fontColor = '#FFFFFF';
    }
    sheet.getRangeByIndex(row, 1).setText('Reporte de Ventas');
    row++;

    // Row 2: Business name
    for (var i = 0; i < 8; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.cellStyle.fontSize = 11;
      cell.cellStyle.backColor = '#283593';
      cell.cellStyle.fontColor = '#E8EAF6';
    }
    sheet.getRangeByIndex(row, 1).setText(headerInfo.businessName);
    row++;

    // Row 3: Date + Vendedor
    for (var i = 0; i < 8; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.cellStyle.fontSize = 9;
      cell.cellStyle.backColor = '#3949AB';
      cell.cellStyle.fontColor = '#E8EAF6';
    }
    final reportDate = DateFormat('dd/MM/yyyy HH:mm').format(session.openingTime);
    sheet.getRangeByIndex(row, 1).setText('$reportDate  |  Vendedor: $sellerName');
    row++;

    // Empty separator
    row++;

    // === TABLE HEADER ===
    final headers = ['Producto', 'Inicio', 'Entrada', 'Disponible', 'Vendido', 'Final', 'Costo', 'Ventas'];
    for (var i = 0; i < headers.length; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.setText(headers[i]);
      cell.cellStyle.bold = true;
      cell.cellStyle.backColor = '#CE93D8';
      cell.cellStyle.fontColor = '#FFFFFF';
      cell.cellStyle.hAlign = xlsx.HAlignType.center;
    }
    final headerRow = row;
    row++;

