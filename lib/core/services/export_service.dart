    final workbook = xlsx.Workbook();
    final sheet = workbook.worksheets[0];
    sheet.name = 'Caja';

    // Write professional header block, then continue from the returned row
    final colSpan = 10;
    int row = _writeExcelHeader(
      sheet: sheet,
      info: headerInfo,
      reportTitle:
          'Informe de Caja - $sellerName - ${DateFormat('dd/MM/yyyy').format(session.openingTime)}',
      colSpan: colSpan,
    );

    void writeHeader(String text, int cs) {
      for (var i = 0; i < cs; i++) {
        final cell = sheet.getRangeByIndex(row, i + 1);
        cell.cellStyle.bold = true;
        cell.cellStyle.backColor = '#6A1B9A';
        cell.cellStyle.fontColor = '#FFFFFF';
      }
      sheet.getRangeByIndex(row, 1).setText(text);
      row++;
    }

    void writeLabelValue(
      String label,
      String value, {
      bool boldValue = false,
      String? fontColor,
    }) {
      sheet.getRangeByIndex(row, 1).setText(label);
      sheet.getRangeByIndex(row, 1).cellStyle.bold = true;
      sheet.getRangeByIndex(row, 2).setText(value);
      if (boldValue) sheet.getRangeByIndex(row, 2).cellStyle.bold = true;
      if (fontColor != null)
        sheet.getRangeByIndex(row, 2).cellStyle.fontColor = fontColor;
      row++;
    }

