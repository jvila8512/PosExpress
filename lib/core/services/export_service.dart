  Future<String> exportReporteVentasPorFechasExcel(
    DateTime from,
    DateTime to,
  ) async {
    final start = DateTime(from.year, from.month, from.day);
    final end = DateTime(to.year, to.month, to.day, 23, 59, 59);
    final orders = await _db.getAllPaidOrdersInRange(start, end);
    final headerInfo = await _getReportHeaderInfo();

    // Aggregate products sold
    final productsData = <String, Map<String, dynamic>>{};
    double totalVentas = 0;
    int totalTransacciones = orders.length;
    for (final order in orders) {
      totalVentas += order.totalAmount;
      final items = await _db.getOrderItems(order.id);
      for (final item in items) {
        final name = item.productName;
        if (productsData.containsKey(name)) {
          productsData[name]!['vendido'] =
              (productsData[name]!['vendido'] as double) + item.quantity;
          productsData[name]!['costoTotal'] =
              (productsData[name]!['costoTotal'] as double) +
              (item.costPrice * item.quantity);
        } else {
          productsData[name] = {
            'vendido': item.quantity,
            'costoTotal': item.costPrice * item.quantity,
            'costPrice': item.costPrice,
          };
        }
      }
    }

    final workbook = xlsx.Workbook();
    final sheet = workbook.worksheets[0];
    sheet.name = 'Reporte de Ventas';

    int row = 1;

    // Row 1: Title
    for (var i = 0; i < 8; i++) {
