      if (stock <= 0) continue;

      final avgCost = stock > 0 ? totalCost / stock : p.costPrice;
      final costValue = totalCost;
      final saleValue = stock * p.unitPrice;
      totalCostValue += costValue;
      totalSaleValue += saleValue;

      data.add([
        p.name,
        stock.toStringAsFixed(0),
        '\$${avgCost.toStringAsFixed(2)}',
        '\$${costValue.toStringAsFixed(2)}',
        '\$${p.unitPrice.toStringAsFixed(2)}',
        '\$${saleValue.toStringAsFixed(2)}',
      ]);

      // Lot detail rows
      for (final lot in lots) {
        if (lot.remainingQuantity <= 0) continue;
        data.add([
          '   Lote #${lot.id} - ${lot.supplier ?? "S/Prov."} - ${_dateFormatter.format(lot.purchaseDate)}',
          lot.remainingQuantity.toStringAsFixed(0),
          '\$${lot.costPerUnit.toStringAsFixed(2)}',
          '\$${(lot.remainingQuantity * lot.costPerUnit).toStringAsFixed(2)}',
          '',
          '',
        ]);
      }
    }

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4.landscape,
        margin: const pw.EdgeInsets.all(32),
        header: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: _buildPdfHeader(
            info: headerInfo,
            reportTitle: 'Informe de Inventario',
          ),
        ),
        footer: (context) => pw.Container(
          alignment: pw.Alignment.centerRight,
          margin: const pw.EdgeInsets.only(top: 12),
          child: pw.Text(
            'Pagina ${context.pageNumber} de ${context.pagesCount}',
            style: const pw.TextStyle(fontSize: 9),
          ),
        ),
        build: (context) => [
          pw.TableHelper.fromTextArray(
            context: context,
            headers: [
              'Producto',
              'Stock',
              'Costo Unit.',
              'Valor Costo',
              'Precio Venta',
              'Valor Venta',
            ],
            data: data,
            headerStyle: pw.TextStyle(
              fontWeight: pw.FontWeight.bold,
              fontSize: 9,
            ),
            headerDecoration: const pw.BoxDecoration(color: PdfColors.green300),
            cellStyle: const pw.TextStyle(fontSize: 8),
            cellAlignment: pw.Alignment.centerRight,
            cellAlignments: {0: pw.Alignment.centerLeft},
            columnWidths: {
              0: const pw.FlexColumnWidth(3),
              1: const pw.FlexColumnWidth(1),
              2: const pw.FlexColumnWidth(1.5),
              3: const pw.FlexColumnWidth(1.5),
              4: const pw.FlexColumnWidth(1.5),
              5: const pw.FlexColumnWidth(1.5),
            },
          ),
          pw.SizedBox(height: 16),
          pw.Divider(),
          pw.SizedBox(height: 8),
