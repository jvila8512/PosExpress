    final sortedProducts = productsData.entries.toList()
      ..sort((a, b) => a.key.compareTo(b.key));

    final dataStartRow = row;
    for (final entry in sortedProducts) {
      final name = entry.key;
      final data = entry.value;
      final vendido = data['vendido'] as double;
      final inicio = openStock[name] ?? 0;
      final final_ = closeStock[name] ?? 0;
      final costoUnit = data['costPrice'] as double;

      sheet.getRangeByIndex(row, 1).setText(name);
      sheet.getRangeByIndex(row, 2).setNumber(inicio);       // Inicio
      sheet.getRangeByIndex(row, 3).setNumber(0);            // Entrada = 0
      // Disponible = Inicio + Entrada (formula)
      sheet.getRangeByIndex(row, 4).setFormula('B$row+C$row');
      sheet.getRangeByIndex(row, 5).setNumber(vendido);      // Vendido
      // Final = Disponible - Vendido (formula)
      sheet.getRangeByIndex(row, 6).setFormula('D$row-E$row');
      sheet.getRangeByIndex(row, 7).setNumber(costoUnit);    // Costo unitario
      // Ventas = Vendido * Costo (formula)
      sheet.getRangeByIndex(row, 8).setFormula('E$row*G$row');
      sheet.getRangeByIndex(row, 7).numberFormat = _currencyFormat;
      sheet.getRangeByIndex(row, 8).numberFormat = _currencyFormat;

      row++;
    }

    final dataEndRow = row - 1;

    // === TOTAL ROW ===
    for (var i = 0; i < 8; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.cellStyle.bold = true;
      cell.cellStyle.backColor = '#E0E0E0';
