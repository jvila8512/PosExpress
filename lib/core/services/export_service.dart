    writeLabelValue('Apertura', _dateFormatter.format(session.openingTime));
    writeLabelValue(
      'Cierre',
      session.closingTime != null
          ? _dateFormatter.format(session.closingTime!)
          : 'Abierta',
    );
    writeLabelValue('Descripcion', session.description ?? '-');
    writeLabelValue(
      'Efectivo Inicial',
      '\$${session.openingCash.toStringAsFixed(2)}',
    );
    writeLabelValue(
      'Efectivo Final',
      session.closingCash != null
          ? '\$${session.closingCash!.toStringAsFixed(2)}'
          : '-',
    );
    row++;

    writeLabelValue(
      'Ventas Totales',
      '\$${session.totalSales.toStringAsFixed(2)}',
      boldValue: true,
    );
    writeLabelValue('Efectivo (neto)', '\$${session.totalCash.toStringAsFixed(2)}');
    final expectedCash = session.openingCash + session.totalCash;
    writeLabelValue(
      'Efectivo Esperado',
      '\$${expectedCash.toStringAsFixed(2)}',
      boldValue: true,
    );
    if (session.closingCash != null) {
      final difference = session.closingCash! - expectedCash;
      final diffColor = difference.abs() < 0.01 ? '#2E7D32' : (difference > 0 ? '#1565C0' : '#C62828');
      writeLabelValue(
        'Diferencia',
        '\$${difference.toStringAsFixed(2)}',
        boldValue: true,
        fontColor: diffColor,
      );
    }
    writeLabelValue(
      'Transferencia',
      '\$${session.totalTransfer.toStringAsFixed(2)}',
    );
    writeLabelValue(
      'Ganancia',
      '\$${profit.toStringAsFixed(2)}',
      boldValue: true,
      fontColor: '#2E7D32',
    );
    row++;

    writeHeader('DETALLE DE VENTAS', 5);

    final detailHeaders = [
      'Hora',
      'Producto',
      'Cantidad',
      'Precio Unit.',
      'Subtotal',
    ];
    for (var i = 0; i < detailHeaders.length; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.setText(detailHeaders[i]);
      cell.cellStyle.bold = true;
      cell.cellStyle.backColor = '#CE93D8';
      cell.cellStyle.fontColor = '#FFFFFF';
    }
    row++;

    // Collect transfer payments for the second table
    final transferPayments = <OrderPayment>[];

    for (final order in orders) {
      final items = await _db.getOrderItems(order.id);
      final payments = await _db.getOrderPayments(order.id);
      final payMethod = payments.map((p) => p.paymentMethod).join(' + ');

      for (final p in payments) {
        if (p.paymentMethod == 'transferencia' && p.amount > 0) {
          transferPayments.add(p);
        }
      }

      for (final item in items) {
        sheet
            .getRangeByIndex(row, 1)
            .setText(
              order.paidAt != null
                  ? DateFormat('HH:mm').format(order.paidAt!)
                  : '-',
            );
        sheet.getRangeByIndex(row, 2).setText(item.productName);
