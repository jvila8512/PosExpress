  Future<String> _getSellerName(String sellerId) async {
    // First try by ID
    var user = await _db.getUserById(sellerId);
    if (user != null) return user.fullName;
    // Fallback: buscar por username (para IDs viejos como 'admin')
    final allUsers = await _db.getAllUsers();
    user = allUsers.where((u) => u.username == sellerId).firstOrNull;
    if (user != null) return user.fullName;
    // Si el usuario existe pero está desactivado
    user = allUsers.where((u) => u.id == sellerId).firstOrNull;
    if (user != null) return '${user.fullName} (inactivo)';
    return 'Vendedor eliminado';
  }

