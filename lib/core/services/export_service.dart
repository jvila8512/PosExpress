  /// PDF interno de transferencias con filtro opcional por tipo
  Future<String> _exportSessionTransferPdf(Session session, String? typeFilter) async {
    final orders = await _db.getPaidOrdersBySession(session.id);
    final sellerName = await _getSellerName(session.userId);
    final headerInfo = await _getReportHeaderInfo();

    final allPayments = <OrderPayment>[];
    for (final order in orders) {
      final payments = await _db.getOrderPayments(order.id);
      for (final p in payments) {
        if (p.paymentMethod == 'transferencia' && p.amount > 0) {
          allPayments.add(p);
        }
      }
    }

    // Filter by type if needed
    final filtered = typeFilter != null
        ? allPayments.where((p) {
            final bank = p.bank?.isNotEmpty == true ? p.bank! : 'Bancaria';
            return bank == typeFilter;
          }).toList()
        : allPayments;

    final dateStr = DateFormat('dd/MM/yyyy').format(session.openingTime);
    final fileDate = DateFormat('yyyy-MM-dd').format(session.openingTime);
    final title = typeFilter != null
        ? 'Transferencias $typeFilter - $dateStr'
        : 'Todas las Transferencias - $dateStr';

    final pdf = pw.Document(title: title, author: 'NegocioJV');

    // Group by type
    final grouped = <String, List<OrderPayment>>{};
    for (final p in filtered) {
      final bank = p.bank?.isNotEmpty == true ? p.bank! : 'Bancaria';
      grouped.putIfAbsent(bank, () => []).add(p);
    }

    // Build table data
    final tableData = <List<String>>[];
    double totalAmount = 0;
    for (final entry in grouped.entries) {
      // Type header row
      final typeTotal = entry.value.fold<double>(0, (s, p) => s + p.amount);
      tableData.add([entry.key, '', '\$${typeTotal.toStringAsFixed(2)}', '', '', '', '']);
      for (final p in entry.value) {
        tableData.add([
          DateFormat('HH:mm').format(p.createdAt),
          '\$${p.amount.toStringAsFixed(2)}',
          p.transactionId ?? '-',
          p.clientName ?? '-',
          p.clientPhone ?? '-',
          p.clientCI ?? '-',
          p.transferDate ?? '-',
        ]);
        totalAmount += p.amount;
      }
    }

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        header: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: _buildPdfHeader(
            info: headerInfo,
            reportTitle: title,
          ),
        ),
        footer: (context) => pw.Container(
          alignment: pw.Alignment.centerRight,
          margin: const pw.EdgeInsets.only(top: 12),
          child: pw.Text(
            'Pagina ${context.pageNumber} de ${context.pagesCount}',
            style: const pw.TextStyle(fontSize: 9),
          ),
        ),
        build: (context) => [
          pw.Container(
            padding: const pw.EdgeInsets.all(12),
            decoration: const pw.BoxDecoration(
              color: PdfColors.purple50,
              borderRadius: pw.BorderRadius.all(pw.Radius.circular(8)),
            ),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text('Vendedor: $sellerName', style: const pw.TextStyle(fontSize: 12)),
                pw.SizedBox(height: 4),
                pw.Text('Fecha: $dateStr', style: const pw.TextStyle(fontSize: 11)),
                pw.Text('Apertura: ${DateFormat('HH:mm').format(session.openingTime)}', style: const pw.TextStyle(fontSize: 11)),
                pw.SizedBox(height: 8),
                pw.Text(
                  'Total Transferencias: \$${totalAmount.toStringAsFixed(2)}',
                  style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.purple700),
                ),
                pw.Text(
                  'Cantidad: ${filtered.length} transferencia${filtered.length != 1 ? 's' : ''}',
                  style: const pw.TextStyle(fontSize: 11),
                ),
                // Subtotals by type
                if (grouped.length > 1) ...[
                  pw.SizedBox(height: 8),
                  ...grouped.entries.map((e) => pw.Text(
                    '${e.key}: ${e.value.length} - \$${e.value.fold<double>(0, (s, p) => s + p.amount).toStringAsFixed(2)}',
                    style: const pw.TextStyle(fontSize: 10),
                  )),
                ],
              ],
            ),
          ),
          pw.SizedBox(height: 16),
          if (filtered.isEmpty)
            pw.Text('No hay transferencias en esta caja', style: const pw.TextStyle(fontSize: 11, color: PdfColors.grey))
          else
            pw.TableHelper.fromTextArray(
              context: context,
              headers: ['Hora', 'Monto', 'No. Trans.', 'Nombre', 'Celular', 'CI', 'Fecha'],
              data: tableData,
              headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 8),
              headerDecoration: const pw.BoxDecoration(color: PdfColors.purple300),
              cellStyle: const pw.TextStyle(fontSize: 7),
              cellAlignments: {
                0: pw.Alignment.center,
                1: pw.Alignment.centerRight,
                6: pw.Alignment.center,
              },
              columnWidths: {
                0: const pw.FlexColumnWidth(1),
                1: const pw.FlexColumnWidth(1.5),
                2: const pw.FlexColumnWidth(2),
                3: const pw.FlexColumnWidth(2.5),
                4: const pw.FlexColumnWidth(1.8),
                5: const pw.FlexColumnWidth(1.2),
                6: const pw.FlexColumnWidth(1.5),
              },
            ),
          pw.SizedBox(height: 12),
          pw.Divider(),
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.end,
            children: [
              pw.Text('Total: ', style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 12)),
              pw.Text(
                '\$${totalAmount.toStringAsFixed(2)}',
                style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 14, color: PdfColors.purple700),
              ),
            ],
          ),
        ],
      ),
    );

    final bytes = await pdf.save();
    final dir = await _getExportsDir();
    final sellerClean = sellerName.replaceAll(' ', '_');
    final filterLabel = typeFilter != null ? '_${typeFilter.replaceAll(' ', '_')}' : '_Todas';
