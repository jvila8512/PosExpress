  Future<String> exportSingleInvoiceExcel(PurchaseInvoice invoice) async {
    final items = await _db.getInvoiceItems(invoice.id);
    final headerInfo = await _getReportHeaderInfo();

    final workbook = xlsx.Workbook();
    final sheet = workbook.worksheets[0];
    sheet.name = 'Factura';

    final colCount = 5;
    final dataStartRow = _writeExcelHeader(
      sheet: sheet,
      info: headerInfo,
      reportTitle: 'Factura ${invoice.invoiceNumber}',
      colSpan: colCount,
    );

    // Info rows
    sheet.getRangeByIndex(dataStartRow, 1).setText('Factura:');
    sheet.getRangeByIndex(dataStartRow, 1).cellStyle.bold = true;
    sheet.getRangeByIndex(dataStartRow, 2).setText(invoice.invoiceNumber);
    sheet.getRangeByIndex(dataStartRow + 1, 1).setText('Fecha:');
    sheet.getRangeByIndex(dataStartRow + 1, 1).cellStyle.bold = true;
    sheet
        .getRangeByIndex(dataStartRow + 1, 2)
        .setText(_dateFormatter.format(invoice.invoiceDate));
    if (invoice.supplier != null && invoice.supplier!.isNotEmpty) {
      sheet.getRangeByIndex(dataStartRow + 2, 1).setText('Proveedor:');
      sheet.getRangeByIndex(dataStartRow + 2, 1).cellStyle.bold = true;
      sheet.getRangeByIndex(dataStartRow + 2, 2).setText(invoice.supplier!);
    }
    if (invoice.notes != null && invoice.notes!.isNotEmpty) {
      sheet.getRangeByIndex(dataStartRow + 3, 1).setText('Notas:');
      sheet.getRangeByIndex(dataStartRow + 3, 1).cellStyle.bold = true;
      sheet.getRangeByIndex(dataStartRow + 3, 2).setText(invoice.notes!);
    }

    final headerRow = dataStartRow + 5;
    final headers = [
      'Producto',
      'Cantidad',
      'Costo Unitario',
      'Total',
      'Subtotal',
    ];
    for (var i = 0; i < headers.length; i++) {
      final cell = sheet.getRangeByIndex(headerRow, i + 1);
      cell.setText(headers[i]);
      cell.cellStyle.bold = true;
      cell.cellStyle.backColor = '#2E7D32';
      cell.cellStyle.fontColor = '#FFFFFF';
      if (i > 0) cell.cellStyle.hAlign = xlsx.HAlignType.center;
    }

    var row = headerRow + 1;
    for (final item in items) {
      sheet.getRangeByIndex(row, 1).setText(item.productName);
      final qtyCell = sheet.getRangeByIndex(row, 2);
      qtyCell.setNumber(item.quantity);
      qtyCell.cellStyle.hAlign = xlsx.HAlignType.center;
      final costCell = sheet.getRangeByIndex(row, 3);
      costCell.setNumber(item.costPerUnit);
      costCell.numberFormat = _currencyFormat;
      costCell.cellStyle.hAlign = xlsx.HAlignType.center;
      final totalCell = sheet.getRangeByIndex(row, 4);
      totalCell.setNumber(item.total);
      totalCell.numberFormat = _currencyFormat;
      totalCell.cellStyle.hAlign = xlsx.HAlignType.center;
      // Subtotal is same as total for invoice items
      final subCell = sheet.getRangeByIndex(row, 5);
      subCell.setNumber(item.total);
      subCell.numberFormat = _currencyFormat;
      subCell.cellStyle.hAlign = xlsx.HAlignType.center;
      row++;
    }

    // Total row
    sheet.getRangeByIndex(row, 4).setText('TOTAL:');
    sheet.getRangeByIndex(row, 4).cellStyle.bold = true;
    sheet.getRangeByIndex(row, 5).setNumber(invoice.totalAmount);
    sheet.getRangeByIndex(row, 5).numberFormat = _currencyFormat;
    sheet.getRangeByIndex(row, 5).cellStyle.bold = true;

    sheet.getRangeByName('A1:E$row').autoFitColumns();

    final bytes = workbook.saveAsStream();
    workbook.dispose();

    final dir = await _getExportsDir();
    final fileName =
        'Factura_${invoice.invoiceNumber.replaceAll(' ', '_')}_${DateFormat('yyyy-MM-dd').format(invoice.invoiceDate)}.xlsx';
    final file = File('$dir/$fileName');
    await file.writeAsBytes(bytes);

    return file.path;
  }

