  final _dateFormatter = DateFormat('dd/MM/yyyy HH:mm');
  final _fileDateFormatter = DateFormat('yyyy-MM-dd_HHmm');

  Future<String> _getExportsDir() async {
    final dir = await getApplicationDocumentsDirectory();
    final exportsDir = Directory('${dir.path}/exports');
    if (!await exportsDir.exists()) {
      await exportsDir.create(recursive: true);
    }
    return exportsDir.path;
  }

  /// Loads business info + current user for report headers
  Future<ReportHeaderInfo> _getReportHeaderInfo() async {
    final storage = KeyValueStorageService();
    final secureStorage = const FlutterSecureStorage();

    final bName = await storage.getValue('business_name') ?? '';
    final bPhone = await storage.getValue('business_phone') ?? '';
    final userId = await secureStorage.read(key: 'user_id') ?? '';

    String userName = 'Usuario';
    if (userId.isNotEmpty) {
      final user = await _db.getUserById(userId);
      if (user != null) userName = user.fullName;
    }

    final now = DateTime.now();
    final generatedAt =
        '${DateFormat('dd/MM/yyyy').format(now)} ${DateFormat('HH:mm').format(now)}';

    return ReportHeaderInfo(
      businessName: bName.isNotEmpty ? bName : 'NegocioJV',
      businessPhone: bPhone,
      generatedBy: userName,
      generatedAt: generatedAt,
    );
  }

  /// Writes a professional header block in an Excel sheet.
  /// Returns the next available row number after the header.
  int _writeExcelHeader({
    required xlsx.Worksheet sheet,
    required ReportHeaderInfo info,
    required String reportTitle,
    required int colSpan,
    int startRow = 1,
  }) {
    int row = startRow;

    // Row 1: Business name (bold, large)
    for (var i = 0; i < colSpan; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.cellStyle.bold = true;
      cell.cellStyle.fontSize = 14;
      cell.cellStyle.backColor = '#1A237E';
      cell.cellStyle.fontColor = '#FFFFFF';
    }
    sheet.getRangeByIndex(row, 1).setText(info.businessName);
    row++;

    // Row 2: Phone (if available)
    if (info.businessPhone.isNotEmpty) {
      for (var i = 0; i < colSpan; i++) {
        final cell = sheet.getRangeByIndex(row, i + 1);
        cell.cellStyle.fontSize = 10;
        cell.cellStyle.backColor = '#283593';
        cell.cellStyle.fontColor = '#E8EAF6';
      }
      sheet.getRangeByIndex(row, 1).setText('Tel: ${info.businessPhone}');
      row++;
    }

    // Row 3: Report title
    for (var i = 0; i < colSpan; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.cellStyle.bold = true;
      cell.cellStyle.fontSize = 12;
      cell.cellStyle.backColor = '#3949AB';
      cell.cellStyle.fontColor = '#FFFFFF';
    }
    sheet.getRangeByIndex(row, 1).setText(reportTitle);
    row++;

    // Row 4: Generated by + date
    for (var i = 0; i < colSpan; i++) {
      final cell = sheet.getRangeByIndex(row, i + 1);
      cell.cellStyle.fontSize = 9;
      cell.cellStyle.backColor = '#5C6BC0';
      cell.cellStyle.fontColor = '#E8EAF6';
    }
    sheet
        .getRangeByIndex(row, 1)
        .setText(
          'Generado por: ${info.generatedBy}  |  Fecha: ${info.generatedAt}',
        );
    row++;

    // Empty separator row
    row++;

    return row;
  }

