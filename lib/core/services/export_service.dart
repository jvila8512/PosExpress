      cell.setText(headers[i]);
      cell.cellStyle.bold = true;
      cell.cellStyle.backColor = '#6A1B9A';
      cell.cellStyle.fontColor = '#FFFFFF';
    }

    double grandEfectivo = 0;
    double grandTransferencia = 0;
    double grandTotal = 0;

    for (var i = 0; i < rendiciones.length; i++) {
      final r = rendiciones[i];
      final row = dataStartRow + i + 1;
      sheet
          .getRangeByIndex(row, 1)
          .setText(_dateFormatter.format(r.fechaRendicion));
      sheet.getRangeByIndex(row, 2).setText(r.vendedoraNombre);
      sheet.getRangeByIndex(row, 3).setNumber(r.totalEfectivo);
      sheet.getRangeByIndex(row, 3).numberFormat = _currencyFormat;
      sheet.getRangeByIndex(row, 4).setNumber(r.totalTransferencia);
      sheet.getRangeByIndex(row, 4).numberFormat = _currencyFormat;
      sheet.getRangeByIndex(row, 5).setNumber(r.totalGeneral);
      sheet.getRangeByIndex(row, 5).numberFormat = _currencyFormat;
      sheet.getRangeByIndex(row, 6).setNumber(r.totalItems.toDouble());

      // Parse transfer data from rawJson
      String transferDetail = '';
      try {
        final raw = Map<String, dynamic>.from(jsonDecode(r.rawJson) as Map);
        final transferencias = raw['transferencias'] as List<dynamic>? ?? [];
        if (transferencias.isNotEmpty) {
          transferDetail = transferencias
              .map((t) {
                final m = t as Map<String, dynamic>;
                final amount = (m['amount'] as num?)?.toDouble() ?? 0;
                final txId = m['transactionId'] as String? ?? '';
                final name = m['clientName'] as String? ?? '';
                return '${name.isNotEmpty ? name : "Sin nombre"}: \$$amount${txId.isNotEmpty ? " ($txId)" : ""}';
              })
              .join('; ');
        }
      } catch (_) {}
      sheet.getRangeByIndex(row, 7).setText(transferDetail);

      grandEfectivo += r.totalEfectivo;
      grandTransferencia += r.totalTransferencia;
      grandTotal += r.totalGeneral;
    }

    final totalRow = dataStartRow + rendiciones.length + 1;
    sheet.getRangeByIndex(totalRow, 1).setText('TOTALES');
    sheet.getRangeByIndex(totalRow, 1).cellStyle.bold = true;
    sheet.getRangeByIndex(totalRow, 3).setNumber(grandEfectivo);
    sheet.getRangeByIndex(totalRow, 3).numberFormat = _currencyFormat;
    sheet.getRangeByIndex(totalRow, 3).cellStyle.bold = true;
    sheet.getRangeByIndex(totalRow, 4).setNumber(grandTransferencia);
    sheet.getRangeByIndex(totalRow, 4).numberFormat = _currencyFormat;
    sheet.getRangeByIndex(totalRow, 4).cellStyle.bold = true;
    sheet.getRangeByIndex(totalRow, 5).setNumber(grandTotal);
    sheet.getRangeByIndex(totalRow, 5).numberFormat = _currencyFormat;
    sheet.getRangeByIndex(totalRow, 5).cellStyle.bold = true;

    sheet.getRangeByName('A1:G$totalRow').autoFitColumns();

    final bytes = workbook.saveAsStream();
    workbook.dispose();

    final dir = await _getExportsDir();
    final dateRange = fromDate != null && toDate != null
