        sheet.getRangeByIndex(row, 4).numberFormat = _currencyFormat;
        sheet.getRangeByIndex(row, 5).setNumber(item.subtotal);
        sheet.getRangeByIndex(row, 5).numberFormat = _currencyFormat;
        row++;
      }

      sheet.getRangeByIndex(row, 1).setText('');
      sheet.getRangeByIndex(row, 2).setText('Paga: $payMethod');
      sheet.getRangeByIndex(row, 4).setText('Total:');
      sheet.getRangeByIndex(row, 4).cellStyle.bold = true;
