              color: PdfColors.blue50,
              borderRadius: pw.BorderRadius.all(pw.Radius.circular(4)),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceAround,
              children: [
                _pdfMetric('Productos', '${openItems.length}'),
                _pdfMetric('Inicial', '${totalOpenQty.toStringAsFixed(0)}'),
                _pdfMetric('Final', '${totalCloseQty.toStringAsFixed(0)}'),
                _pdfMetric('Costo', '\$${totalCost.toStringAsFixed(2)}'),
              ],
            ),
          ),
          pw.SizedBox(height: 15),
          pw.TableHelper.fromTextArray(
            context: ctx,
            headers: ['Producto', 'Inicial', 'Final', 'Vendido', 'Costo/u', 'Valor Costo', 'Margen %'],
