  /// Opens the system file picker (SAF on Android) for the user to choose
  /// where to save the exported file. Works on all Android versions without
  /// special permissions (no MANAGE_EXTERNAL_STORAGE needed).
  /// Returns the saved file path, or null if the user cancelled.
  Future<String?> saveToDownloads(String filePath) async {
    try {
      final sourceFile = File(filePath);
      if (!await sourceFile.exists()) {
        debugPrint('[saveToDownloads] Source file not found: $filePath');
        return null;
      }

      final fileName = filePath.split('/').last;
      final bytes = await sourceFile.readAsBytes();

      // Use SAF via file_picker — opens the native "Save to..." dialog
      // User picks the folder (Downloads, NegocioJV, etc.)
      final result = await FilePicker.platform.saveFile(
        dialogTitle: 'Guardar en...',
        fileName: fileName,
        bytes: bytes,
      );

      return result; // null = user cancelled
    } catch (e) {
      debugPrint('[saveToDownloads] Error: $e');
      return null;
    }
  }

